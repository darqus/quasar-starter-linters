import { access, readFile, readdir } from 'node:fs/promises'
import path from 'node:path'

import { parse as parseScss } from 'postcss-scss'
import { describe, expect, it } from 'vitest'

const ROOT = path.resolve(import.meta.dirname, '..')
const CSS_DIR = path.join(ROOT, 'src/css')
const ENTRY_POINT = path.join(CSS_DIR, 'app.scss')

/** Layer order is a contract of `_reset.scss` and `app.scss` together. */
const LAYER_ORDER = ['reset', 'tokens', 'base', 'components', 'utilities']

/** Layers a regular partial may use. `reset`, `tokens` and overrides are special. */
const PARTIAL_LAYERS = new Set(['base', 'components', 'utilities'])

/** Partials that are intentionally not wrapped in a single regular layer. */
const SPECIAL_PARTIALS = new Set([
  '_quasar-overrides.scss',
  '_reset.scss',
  '_tokens.scss',
])

async function parseStylesheet(file) {
  const source = await readFile(file, 'utf8')
  return parseScss(source, { from: file })
}

function meaningfulNodes(root) {
  return root.nodes.filter((node) => node.type !== 'comment')
}

function useSpecifiers(root) {
  return meaningfulNodes(root)
    .filter((node) => node.type === 'atrule' && node.name === 'use')
    .map((node) => {
      const match = node.params.match(/^(['"])(.+?)\1/)

      if (!match) {
        throw new Error(`Cannot parse @use parameters: ${node.params}`)
      }

      return match[2]
    })
}

function resolvePartial(specifier) {
  const relative = specifier.replace(/^\.\//, '')
  const directory = path.dirname(relative)
  const basename = `_${path.basename(relative)}.scss`

  return path.join(CSS_DIR, directory, basename)
}

describe('style architecture contract', () => {
  it('keeps app.scss a pure list of @use statements', async () => {
    const root = await parseStylesheet(ENTRY_POINT)
    const unexpected = meaningfulNodes(root).filter(
      (node) => node.type !== 'atrule' || node.name !== 'use',
    )

    expect(unexpected.map((node) => node.toString())).toEqual([])
  })

  it('loads reset first and Quasar overrides last', async () => {
    const root = await parseStylesheet(ENTRY_POINT)
    const specifiers = useSpecifiers(root)

    expect(specifiers[0]).toBe('./reset')
    expect(specifiers.at(-1)).toBe('./quasar-overrides')
  })

  it('references existing partials only', async () => {
    const root = await parseStylesheet(ENTRY_POINT)
    const specifiers = useSpecifiers(root)
    const missing = []

    for (const specifier of specifiers) {
      const file = resolvePartial(specifier)

      try {
        await access(file)
      } catch {
        missing.push(specifier)
      }
    }

    expect(missing).toEqual([])
  })

  it('uses every SCSS partial of src/css', async () => {
    const root = await parseStylesheet(ENTRY_POINT)
    const referenced = new Set(
      useSpecifiers(root).map((specifier) =>
        path.basename(resolvePartial(specifier)),
      ),
    )
    const partials = (await readdir(CSS_DIR))
      .filter((file) => file.startsWith('_') && file.endsWith('.scss'))
      .sort((left, right) => left.localeCompare(right))

    expect(partials).toEqual(
      [...referenced].sort((left, right) => left.localeCompare(right)),
    )
  })

  it('wraps every partial in a regular cascade layer', async () => {
    const partials = (await readdir(CSS_DIR)).filter(
      (file) =>
        file.startsWith('_') &&
        file.endsWith('.scss') &&
        !SPECIAL_PARTIALS.has(file),
    )

    for (const partial of partials) {
      const root = await parseStylesheet(path.join(CSS_DIR, partial))
      const nodes = meaningfulNodes(root)

      expect(nodes, partial).toHaveLength(1)
      expect(nodes[0].type, partial).toBe('atrule')
      expect(nodes[0].name, partial).toBe('layer')
      expect(PARTIAL_LAYERS.has(nodes[0].params), partial).toBe(true)
    }
  })

  it('declares the layer order in _reset.scss', async () => {
    const root = await parseStylesheet(path.join(CSS_DIR, '_reset.scss'))
    const statement = root.nodes.find(
      (node) =>
        node.type === 'atrule' &&
        node.name === 'layer' &&
        node.params.includes(','),
    )

    expect(statement).toBeDefined()
    expect(statement.params.split(',').map((layer) => layer.trim())).toEqual(
      LAYER_ORDER,
    )
  })

  it('keeps _tokens.scss generated', async () => {
    const source = await readFile(path.join(CSS_DIR, '_tokens.scss'), 'utf8')

    expect(source).toContain('GENERATED by scripts/build-tokens.mjs')
    expect(source).toContain('@layer tokens')
  })
})
